package com.hiremate.screening;

/**
 * 서류 전형 전체 지원자 리스트의 정렬 기준. 필수 조건을 채우지 못한 지원자는 어느 기준이든 맨 아래에 선다.
 * 같은 개수면 이름 순이다. 평가 · 면접 전형은 이 기준을 쓰지 않고 점수 높은 순이다.
 */
public enum CandidateSort {
    /** 자격요건 + 우대사항에서 충족한 개수가 많은 순. 처음 정렬이다. */
    BASIC,
    /** 자격요건 + 우대사항 충족 개수에 상으로 판정한 인재상 개수를 더한 값이 많은 순. */
    TALENT
}
