CREATE TABLE job_postings (
    id UUID PRIMARY KEY,
    recruitment_id UUID NOT NULL UNIQUE REFERENCES recruitments (id),
    company_id UUID NOT NULL REFERENCES companies (id),
    title VARCHAR(200) NOT NULL,
    job_category VARCHAR(100) NOT NULL DEFAULT '',
    employment_type VARCHAR(50) NOT NULL DEFAULT '',
    career VARCHAR(50) NOT NULL DEFAULT '',
    location VARCHAR(100) NOT NULL DEFAULT '',
    intro TEXT NOT NULL DEFAULT '',
    duties TEXT NOT NULL DEFAULT '[]',
    qualifications TEXT NOT NULL DEFAULT '[]',
    preferred TEXT NOT NULL DEFAULT '[]',
    benefits TEXT NOT NULL DEFAULT '[]',
    notices TEXT NOT NULL DEFAULT '[]',
    required_extras TEXT NOT NULL DEFAULT '[]',
    pending_suggestion TEXT,
    open_at TIMESTAMP WITH TIME ZONE,
    close_at TIMESTAMP WITH TIME ZONE,
    published_at TIMESTAMP WITH TIME ZONE,
    published_by UUID,
    closed_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
